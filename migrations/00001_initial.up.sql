-- Presentation-only grouping for the balance sheet report: which section an
-- account is shown under (Long-term Assets, Current Assets & Liabilities,
-- Long-term Liabilities, Capital & Reserves). Distinct from
-- ledger_account_type: type drives debit/credit accounting behavior and
-- which side of the equation an account is on, but nothing about
-- account_type says whether an ASSETS account is a current or long-term
-- one - that's business judgment (a laptop vs. a bank account are both
-- ASSETS), hence this separate table.
CREATE TABLE public.balance_sheet_category (
    id INTEGER PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    display_sequence INTEGER DEFAULT 0 NOT NULL
);

-- Presentation-only grouping for the income statement report: which section an EXPENSES/REVENUE
