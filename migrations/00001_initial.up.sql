-- Application user, authenticated via passkeys (WebAuthn) - see
-- webauthn_credential below. email is the human-facing identifier used for
-- account lookup/display and as the WebAuthn "user.name" during passkey
-- registration; the actual credential material lives in
-- webauthn_credential, never here.
CREATE TABLE public.app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    display_name VARCHAR(200),
    -- System-wide, not business-scoped (unlike business_user.role): can create a business
    -- (see auth.RequireGlobalAdmin, BusinessService.CreateBusiness) and invite/manage users on
    -- any business, full stop - nobody else can do either. The very first global admin has no
    -- existing admin to grant it, so it's bootstrapped from DENARIX_BOOTSTRAP_ADMIN_EMAIL at server
    -- startup instead (internal/auth/bootstrap.go); every subsequent one is promoted via
    -- UserService.SetGlobalAdmin, which itself requires an existing global admin to call.
    is_global_admin BOOLEAN DEFAULT FALSE NOT NULL,
    is_active BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMP DEFAULT NOW() NOT NULL,
    updated_at TIMESTAMP DEFAULT NOW() NOT NULL,
    deleted_at TIMESTAMP
);

CREATE UNIQUE INDEX app_user_email_uindex ON public.app_user(email);
-- Enforces "only one global admin" at the DB level as a hard backstop, not just application
-- logic: indexing a constant expression with a partial WHERE clause means at most one row can
-- ever satisfy is_global_admin = TRUE. auth.SetGlobalAdmin transfers admin status (clears the
-- old holder, sets the new one, in one transaction) precisely so it never even attempts to
-- violate this.
CREATE UNIQUE INDEX app_user_single_global_admin_uindex ON public.app_user ((1)) WHERE is_global_admin = TRUE AND deleted_at IS NULL;

-- One row per registered passkey (a user may register more than one - e.g.
-- a MacBook and an iPhone). credential_id/public_key are the raw WebAuthn
-- values as produced by a relying-party library (e.g. go-webauthn/webauthn);
-- sign_count supports its clone-detection check. transports is a
-- comma-separated hint list (usb, nfc, ble, internal, hybrid) rather than
-- an array type, consistent with the rest of the schema avoiding
-- Postgres-specific array/enum types.
CREATE TABLE public.webauthn_credential (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.app_user(id),
    credential_id BYTEA NOT NULL,
    public_key BYTEA NOT NULL,
    attestation_type VARCHAR(50),
    transports VARCHAR(100),
    aaguid BYTEA,
    sign_count BIGINT DEFAULT 0 NOT NULL,
    -- BE ("this credential is capable of being backed up/synced - e.g. via iCloud Keychain -
    -- and should NEVER change") and BS ("it currently *is* backed up/synced - can change").
    -- go-webauthn's FinishPasskeyLogin refuses a login if the ceremony's BE flag doesn't match
    -- what's on file here, so both must be persisted from the registration ceremony - not
    -- storing them at all made this table's BE always false, so every login against a real
    -- backup-eligible authenticator (any Apple platform passkey) failed with "Backup Eligible
    -- flag inconsistency detected during login validation".
    backup_eligible BOOLEAN DEFAULT FALSE NOT NULL,
    backup_state BOOLEAN DEFAULT FALSE NOT NULL,
    name VARCHAR(200),
    created_at TIMESTAMP DEFAULT NOW() NOT NULL,
    last_used_at TIMESTAMP
);

CREATE UNIQUE INDEX webauthn_credential_credential_id_uindex ON public.webauthn_credential(credential_id);
CREATE INDEX webauthn_credential_user_id_idx ON public.webauthn_credential(user_id);

-- credential_enrollment is a single-use, admin-issued (or bootstrap-issued) token that
-- authorizes enrolling a NEW passkey onto an EXISTING app_user. It is the ONLY way to add a
-- credential to an account that already has one: passkey registration derives its identity
-- entirely from the token it is handed (a business_invite for a brand-new account, or one of
-- these for an existing one), never from a free-typed email, so knowing someone's email is not
-- enough to enroll a device against their account. See internal/auth/webauthn.go.
--
--   * purpose RESET     - issued by a global admin or a business OWNER/ADMIN via
--                         UserService.ResetUserCredentials (a lost/replaced device).
--   * purpose BOOTSTRAP - minted for the first global admin at server startup, since they have
--                         no inviter above them (see internal/auth/bootstrap.go).
--
-- revoke_existing (default true, the "reset" semantics) deletes the user's other passkeys when
-- this token is redeemed, so a lost device can't still sign in; false just adds a device.
-- Revocation happens at REDEMPTION, not when the token is minted, so minting one is
-- non-destructive (a break-glass restart that re-mints does not wipe a working credential).
CREATE TABLE public.credential_enrollment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.app_user(id),
    token_hash VARCHAR(64) NOT NULL,
    revoke_existing BOOLEAN NOT NULL DEFAULT TRUE,
    purpose VARCHAR(20) NOT NULL DEFAULT 'RESET' CHECK (purpose IN ('RESET', 'BOOTSTRAP')),
    created_by_user_id BIGINT REFERENCES public.app_user(id),
    created_at TIMESTAMP DEFAULT NOW() NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    consumed_at TIMESTAMP
);

CREATE UNIQUE INDEX credential_enrollment_token_hash_uindex ON public.credential_enrollment(token_hash);
CREATE INDEX credential_enrollment_user_id_idx ON public.credential_enrollment(user_id);
-- At most one live (unconsumed, unexpired-by-intent) enrollment per user at a time keeps a
-- break-glass restart loop from piling up tokens; expiry is enforced in the query, not here.
CREATE UNIQUE INDEX credential_enrollment_user_pending_uindex
    ON public.credential_enrollment(user_id) WHERE consumed_at IS NULL;

-- Optimistic concurrency, Kubernetes-style: every row on a table that has this trigger
-- carries a resource_version that this bumps on every UPDATE - any UPDATE, including
-- soft-deletes, status flips, and internal side effects like ConsumeNextInvoiceNumber or
-- ApplyPaymentToInvoice - so it strictly increases with each committed write to the row,
-- and can't be set from the outside (NEW.resource_version is overwritten unconditionally).
-- The API returns it on every read and accepts it back as an optional precondition on every
-- Update*/Deactivate* RPC (`WHERE resource_version = $expected`): a caller holding a stale
-- copy gets ABORTED instead of silently overwriting whoever wrote in between. Unset (0) means
-- unconditional, same as an empty resourceVersion in k8s. See docs/schema.md, "Patterns".
CREATE FUNCTION public.bump_resource_version() RETURNS TRIGGER AS $$
BEGIN
    NEW.resource_version := OLD.resource_version + 1;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

