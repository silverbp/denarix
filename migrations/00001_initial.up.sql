-- A pending grant of business access to an email that hasn't necessarily registered a passkey
-- yet (see AcceptBusinessInvite) - not a business_user row itself, which is only created once
-- accepted. token_hash follows the exact same pattern as user_session.refresh_token_hash: a
-- sha256 digest, never the raw token, which is shown to the inviter exactly once
-- (CreateBusinessInviteResponse) and shared with the invitee out-of-band (Slack, text, email -
-- denarix never sends it itself). Requiring the token (not just knowing the invited email) is what
-- stops anyone who merely guesses/knows an email from claiming access - passkey registration
-- itself has no email-ownership verification (see internal/auth/webauthn.go).
CREATE TABLE public.business_invite (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES public.business(id),
    email VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'MEMBER' CHECK (role IN ('OWNER', 'ADMIN', 'MEMBER', 'VIEWER')),
    token_hash VARCHAR(64) NOT NULL,
    invited_by_user_id BIGINT REFERENCES public.app_user(id),
    created_at TIMESTAMP DEFAULT NOW() NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    accepted_at TIMESTAMP,
    accepted_by_user_id BIGINT REFERENCES public.app_user(id),
    revoked_at TIMESTAMP
);

CREATE UNIQUE INDEX business_invite_token_hash_uindex ON public.business_invite(token_hash);
CREATE INDEX business_invite_business_id_idx ON public.business_invite(business_id);
-- Only one outstanding (not yet accepted or revoked) invite per business+email at a time -
-- re-inviting the same address means revoking the old one first, so there's never ambiguity
-- about which token is actually live.
CREATE UNIQUE INDEX business_invite_business_email_pending_uindex
    ON public.business_invite(business_id, lower(email)) WHERE accepted_at IS NULL AND revoked_at IS NULL;

